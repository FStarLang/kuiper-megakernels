#!/usr/bin/env python3
"""Write the fixed tightness theorem for a typed spec (no agents, no choices).

A typed spec KPlay.Spec (proofs/<p>-spec/KPlay.Spec.fst) is written once over
number types (KPlay.Numbers.number) and defines
  inputs_t a, outputs_t a, input_domain, inputs, outputs,
  spec n1 .. nk x y (k number types, e.g. one for weights, one for scores),
  postcondition x y = spec <float number types> x y
    (the property the kernels are proved to meet).
From the spec alone this script writes KPlay.Tightness.<P>.Statement.fst:
  - the kernels' postcondition is the spec at its float number types;
  - over exact reals (x stands only for x) the spec defines a function:
    some input is in the domain, every input in the domain has an answer,
    and two answers for the same input are equal, field by field.
The only freedoms are the library's, at float number types (KPlay.Numbers):
argmax ties, for FP32 any pick on rows that are not all finite, and a
model constant's exact or float32 value.
KPlay.Tightness.<P>.fst ties the theorem to KPlay.Tightness.<P>.Proof.fst,
and F* checks it. `--check` fails if the generated files differ.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent

FLOATS = {"N.bf16", "N.f32"}
EQUALITY = {"vector": "N.veq", "matrix": "N.meq"}
SCALARS = {"int", "nat", "bool", "token_id"}

STATEMENT = """module KPlay.Tightness.{P}.Statement
(* GENERATED by tightness.py from proofs/{p}-spec/KPlay.Spec.fst. Do not edit. *)
open FStar.Real
module K = KPlay.Spec
module N = KPlay.Numbers

(* The kernels' postcondition is the spec at its float number types. *)
let float_instance : prop =
  forall (x:K.inputs) (y:K.outputs). K.postcondition x y <==> K.spec {num} x y

(* Over exact reals the spec defines a function. *)
let nonempty : prop = exists (x:K.inputs_t real). K.input_domain x

let answers : prop =
  forall (x:K.inputs_t real). K.input_domain x ==>
    (exists (y:K.outputs_t real). K.spec {exact} x y)

let unique : prop =
  forall (x:K.inputs_t real) (y1 y2:K.outputs_t real).
    K.input_domain x /\\ K.spec {exact} x y1 /\\ K.spec {exact} x y2 ==>
    {equal}

let tight : prop = float_instance /\\ nonempty /\\ answers /\\ unique
"""

FINAL = """module KPlay.Tightness.{P}
(* GENERATED by tightness.py. Do not edit. *)
let checked () : Lemma KPlay.Tightness.{P}.Statement.tight =
  KPlay.Tightness.{P}.Proof.proof ()
"""


def numbers_of(text: str) -> list[str]:
    m = re.search(r"^let postcondition \(input:inputs\) \(output:outputs\) : prop =\s*spec((?:\s+N\.\w+)+)\s+input output\s*$",
                  text, re.M)
    nums = m.group(1).split() if m else []
    if not nums or any(n not in FLOATS for n in nums):
        raise SystemExit("spec must declare `let postcondition (input:inputs) (output:outputs) : prop = "
                         "spec <numbers> input output` with numbers in " + ", ".join(sorted(FLOATS)))
    return nums


def spec_shape(text: str) -> tuple[str, str, list[str]]:
    nums = numbers_of(text)
    num, exact = " ".join(nums), " ".join(["N.exact"] * len(nums))
    m = re.search(r"^noeq type outputs_t \(a:Type0\) = \{(.*?)\}", text, re.M | re.S)
    if not m:
        raise SystemExit("spec must declare `noeq type outputs_t (a:Type0) = { ... }`")
    equal = []
    for field in m.group(1).split(";"):
        field = re.sub(r"\(\*.*?\*\)", "", field, flags=re.S).strip()
        if not field:
            continue
        name, _, ty = (s.strip() for s in field.partition(":"))
        head = ty.split()[0]
        if head in EQUALITY:
            equal.append(f"{EQUALITY[head]} y1.K.{name} y2.K.{name}")
        elif ty in SCALARS:
            equal.append(f"y1.K.{name} == y2.K.{name}")
        else:
            raise SystemExit(f"outputs_t field {name}: unsupported type {ty!r} (use vector, matrix or a scalar)")
    return num, exact, equal


def generated(project: str) -> dict[Path, str]:
    P = project.capitalize()
    num, exact, equal = spec_shape((ROOT / "proofs" / f"{project}-spec" / "KPlay.Spec.fst").read_text())
    d = ROOT / "proofs" / f"{project}-tightness"
    return {d / f"KPlay.Tightness.{P}.Statement.fst":
                STATEMENT.format(P=P, p=project, num=num, exact=exact, equal=" /\\\n    ".join(equal)),
            d / f"KPlay.Tightness.{P}.fst": FINAL.format(P=P)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("projects", nargs="+")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = []
    for p in a.projects:
        for path, text in generated(p).items():
            if a.check:
                if not path.exists() or path.read_text() != text:
                    bad.append(path)
            else:
                path.write_text(text)
    for path in bad:
        print(f"differs from tightness.py output: {path.relative_to(ROOT)}", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
