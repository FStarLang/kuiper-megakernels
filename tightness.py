#!/usr/bin/env python3
"""Write the fixed tightness theorem for a spec (no agents, no choices).

Input: proofs/<p>-tightness/KPlay.Tightness.<P>.Question.fst, which lists the
spec's inputs, its complete flat answer, the real target of every output, and
the one declared freedom (`allowed` choices, e.g. argmax ties).
Output (generated, never edited by hand):
  KPlay.Tightness.<P>.Statement.fst  the theorem: every answer the spec accepts
                                     equals its target, up to an allowed choice;
  KPlay.Tightness.<P>.fst            ties it to the proof in
                                     KPlay.Tightness.<P>.Proof.fst (checked by F*).
`--check` fails if the generated files differ from what this script writes.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent

STATEMENT = """module KPlay.Tightness.{P}.Statement
(* GENERATED by tightness.py from KPlay.Tightness.{P}.Question. Do not edit. *)
open Kuiper.Approximates
module Q = KPlay.Tightness.{P}.Question
module A = KPlay.Tightness.Answer
module S = FStar.Seq

type answer = A.answer Q.exact Q.number Q.count

(* The one answer for input x and allowed choice c: the exact part equals its
   target, and for every real model the inputs stand for, every output value
   approximates its real target. *)
let pinned (x:Q.input{{Q.domain x}}) (c:Q.choice x) (y:answer) : prop =
  y.A.exact == Q.exact_target x c /\\
  (forall (m:Q.model). Q.models x m ==>
     (forall (i:nat{{i < Q.count (Q.exact_target x c)}}). i < S.length y.A.numbers ==>
        S.index y.A.numbers i %~ S.index (Q.number_target x m c) i))

(* The spec is tight: its domain is not empty, and every answer it accepts is
   the pinned answer for some allowed choice. *)
let tight : prop =
  (exists (x:Q.input). Q.domain x) /\\
  (forall (x:Q.input{{Q.domain x}}) (y:answer).
     Q.spec x y ==> (exists (c:Q.choice x). Q.allowed x c /\\ pinned x c y))
"""

FINAL = """module KPlay.Tightness.{P}
(* GENERATED by tightness.py. Do not edit. *)
let checked () : Lemma KPlay.Tightness.{P}.Statement.tight =
  KPlay.Tightness.{P}.Proof.proof ()
"""


def generated(project: str) -> dict[Path, str]:
    P = project.capitalize()
    d = ROOT / "proofs" / f"{project}-tightness"
    if not (d / f"KPlay.Tightness.{P}.Question.fst").exists():
        raise SystemExit(f"missing {d}/KPlay.Tightness.{P}.Question.fst")
    return {d / f"KPlay.Tightness.{P}.Statement.fst": STATEMENT.format(P=P),
            d / f"KPlay.Tightness.{P}.fst": FINAL.format(P=P)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("projects", nargs="+")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = []
    for p in a.projects:
        for path, text in generated(p).items():
            if a.check:
                if not path.exists() or path.read_text() != text:
                    bad.append(path)
            else:
                path.write_text(text)
    for path in bad:
        print(f"differs from tightness.py output: {path.relative_to(ROOT)}", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
